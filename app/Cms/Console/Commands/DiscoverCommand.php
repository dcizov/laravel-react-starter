<?php

declare(strict_types=1);

namespace App\Cms\Console\Commands;

use App\Cms\Registries\Navigation;
use App\Cms\Repositories\AddonRepository;
use App\Cms\Repositories\ThemeRepository;
use Illuminate\Console\Command;
use Illuminate\Database\QueryException;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\File;

/**
 * `php artisan lattice:discover`
 *
 * Regenerates the TypeScript registries the frontend imports and flushes the
 * extension caches. JS is resolved at build time — never fetched at runtime.
 */
class DiscoverCommand extends Command
{
    protected $signature = 'lattice:discover';

    protected $description = 'Rebuild the generated frontend registries and flush extension caches';

    public function handle(AddonRepository $addons, ThemeRepository $themes, Navigation $navigation): int
    {
        $path = (string) config('lattice.generated_path');
        File::ensureDirectoryExists($path);

        // The registries are build inputs, and a build may run before the
        // database exists (fresh clone, CI, a container image build). In that
        // case write the neutral registry — core navigation, no active addons —
        // so `npm run build` and `tsc` are reproducible from the repository
        // without a migrated database.
        try {
            $items = $this->navigationItems($addons);
            $installed = $addons->installed();
        } catch (QueryException) {
            $this->components->warn('Database not ready: writing the neutral registry.');

            $items = config('lattice.core_navigation', []);
            $installed = [];
        }

        $this->writeNavigation($path, $items);
        $this->writeAddons($path, $installed);

        $this->flushCaches($addons, $themes, $navigation);

        $this->components->info("Registries written to {$path}");

        return self::SUCCESS;
    }

    /**
     * Core navigation plus every active addon's manifest navigation, exactly
     * like the runtime registry.
     *
     * @return list<array<string, mixed>>
     */
    private function navigationItems(AddonRepository $addons): array
    {
        $items = config('lattice.core_navigation', []);

        foreach ($addons->activeManifests() as $manifest) {
            foreach ($manifest->navigation as $item) {
                $items[] = $item;
            }
        }

        return $items;
    }

    private function flushCaches(AddonRepository $addons, ThemeRepository $themes, Navigation $navigation): void
    {
        try {
            $addons->flushCache();
            $themes->flushCache();
            $navigation->flush();
        } catch (QueryException) {
            return;
        }

        foreach (config('lattice.cache.keys') as $key) {
            Cache::forget((string) $key);
        }
    }

    /**
     * @param  list<array<string, mixed>>  $items
     */
    private function writeNavigation(string $path, array $items): void
    {

        $sections = [];

        foreach ($items as $item) {
            $sections[$item['section']][] = [
                'label' => $item['label'],
                'route' => $item['route'],
                'icon' => $item['icon'] ?? null,
            ];
        }

        ksort($sections);

        $lines = [];

        foreach ($sections as $section => $items) {
            $lines[] = '    {';
            $lines[] = '        label: '.$this->js($section).',';
            $lines[] = '        items: [';
            foreach ($items as $item) {
                $lines[] = '            { label: '.$this->js($item['label']).', route: '.$this->js($item['route']).', icon: '.$this->js($item['icon']).' },';
            }
            $lines[] = '        ],';
            $lines[] = '    },';
        }

        $body = implode("\n", $lines);

        File::put($path.'/navigation.ts', <<<TS
        // Generated by `php artisan lattice:discover`. Do not edit by hand.

        export type GeneratedNavItem = {
            label: string;
            route: string;
            icon: string | null;
        };

        export type GeneratedNavSection = {
            label: string;
            items: GeneratedNavItem[];
        };

        export const navigationSections: GeneratedNavSection[] = [
        {$body}
        ];

        TS);
    }

    /**
     * @param  list<object>  $installed
     */
    private function writeAddons(string $path, array $installed): void
    {
        // No timestamp: identical state has to produce identical bytes, so the
        // generated tooling output stays diffable and cacheable.
        $manifest = [
            'addons' => array_map(fn ($row): array => [
                'handle' => $row->handle,
                'name' => $row->name,
                'version' => $row->version,
                'status' => $row->status,
            ], $installed),
        ];

        File::put($path.'/addons.ts', "// Generated by `php artisan lattice:discover`. Do not edit by hand.\n\nexport const addonRegistry = ".json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)." as const;\n");
    }

    private function js(?string $value): string
    {
        return $value === null ? 'null' : json_encode($value, JSON_UNESCAPED_SLASHES);
    }
}
